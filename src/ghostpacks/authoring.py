"""Authoring helper: `ghostpacks init-pack <project>`.

Turns a project's tuned .ghostslice.json into a draft pack folder:
a pack.json manifest skeleton (kind: context, unscored, today's date)
and the profile as profile.json. Absolute paths are stripped (dropped
from list sections, listed in the result and in the draft NOTES) so a
draft never leaks the author's machine layout. The draft is data only
and still needs `ghostpacks lint` (and a GhostBench run before it may
claim a score) -- init-pack says so in the files it writes.
"""
from __future__ import annotations

import json
import re
from datetime import date
from pathlib import Path

from .manager import load_project_profile
from .pack import GhostPacksError, _is_absolute, validate_profile_fragment

LIST_KEYS = ("ignore", "entry_points", "plugins")


def _slug(text: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return slug or "my-pack"


def create_pack_from_project(project, out_dir, pack_id=None, name=None,
                             author=None, stack_tags=None, force=False) -> dict:
    project = Path(project)
    out_dir = Path(out_dir)
    profile, raw = load_project_profile(project)
    if raw is None:
        raise GhostPacksError(
            f"{project}: no .ghostslice.json to turn into a pack; tune a "
            "profile with GhostSlice first")
    if out_dir.exists() and any(out_dir.iterdir()) and not force:
        raise GhostPacksError(
            f"{out_dir}: already exists and is not empty; pass --force to "
            "overwrite the draft files")
    stripped = []
    fragment = json.loads(json.dumps(profile))
    fragment.pop("path", None)
    for key in LIST_KEYS:
        kept = []
        for item in fragment.get(key) or []:
            if _is_absolute(item):
                stripped.append(f"{key}: {item}")
            else:
                kept.append(item)
        if kept:
            fragment[key] = kept
        else:
            fragment.pop(key, None)
    modes = {}
    for pat, mode in (fragment.get("modes") or {}).items():
        if _is_absolute(pat):
            stripped.append(f"modes: {pat}")
        else:
            modes[pat] = mode
    if modes:
        fragment["modes"] = modes
    else:
        fragment.pop("modes", None)
    validate_profile_fragment(fragment, where="draft profile fragment")
    pid = _slug(pack_id or project.name)
    manifest = {
        "id": pid,
        "name": name or pid.replace("-", " ").title() + " (draft)",
        "version": "0.1.0",
        "kind": "context",
        "description": "Draft pack generated by ghostpacks init-pack from a "
                       "tuned project profile. Review every entry before sharing.",
        "stack_tags": list(stack_tags or []),
        "ghostslice": ">=1.0.0,<2.0.0",
        "author": author or "",
        "date": date.today().isoformat(),
        "reference_projects": [],
        "bench_report": None,
        "score": None,
    }
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "pack.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (out_dir / "profile.json").write_text(
        json.dumps(fragment, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    notes = [
        f"# {pid} (draft pack)",
        "",
        "Generated by `ghostpacks init-pack`. Status: unscored, unreviewed draft.",
        "Before sharing: read profile.json top to bottom, run `ghostpacks lint`,",
        "and run GhostBench Tier A on a stated reference project before claiming",
        "any score in pack.json.",
        "",
    ]
    if stripped:
        notes.append("Absolute paths stripped during generation (not carried into the pack):")
        notes += [f"- {item}" for item in stripped]
        notes.append("")
    (out_dir / "NOTES.md").write_text("\n".join(notes), encoding="utf-8")
    return {"pack_id": pid, "out_dir": str(out_dir), "stripped": stripped,
            "files": ["pack.json", "profile.json", "NOTES.md"],
            "score_status": "unscored"}
